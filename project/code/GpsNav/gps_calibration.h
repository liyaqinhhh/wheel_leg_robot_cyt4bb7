float   gps_cal_get_offset(void);        // 获取当前偏移量
void    gps_cal_reset(void);             // 重置偏移量

//====================================================全局变量====================================================

extern float gps_cal_offset_deg;         // 当前 IMU-GPS 偏移量 [度]

