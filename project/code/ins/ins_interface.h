/*
 * ins_interface.h
 * INS 对外 API 接口声明
 * 所有用户可调用的事件触发函数，无按键/遥控依赖
 */

#ifndef _INS_INTERFACE_H_
#define _INS_INTERFACE_H_

#include "zf_common_typedef.h"
#include "ins_core.h"

 //------------------------------------------- 校准相关 --------------------------------------------------------

//-------------------------------------------------------------------------------------------------------------------
//  @brief      开始陀螺仪零偏校准（静止采样 N 次取均值）
//  @param      void
//  @return     void
//  @note       调用后机器人需保持静止，校准完成后自动生效
//-------------------------------------------------------------------------------------------------------------------
void ins_api_start_gyro_calib(void);

//-------------------------------------------------------------------------------------------------------------------
//  @brief      将校准结果保存到 Flash
//  @param      void
//  @return     void
//-------------------------------------------------------------------------------------------------------------------
void ins_api_save_imu_bias(void);

//-------------------------------------------------------------------------------------------------------------------
//  @brief      从 Flash 加载陀螺仪零偏
//  @param      void
//  @return     void
//-------------------------------------------------------------------------------------------------------------------
void ins_api_load_imu_bias(void);

 //------------------------------------------- 坐标系管理 ------------------------------------------------------

//-------------------------------------------------------------------------------------------------------------------
//  @brief      将当前位置设为原点
//  @param      void
//  @return     void
//-------------------------------------------------------------------------------------------------------------------
void ins_api_set_origin(void);

//-------------------------------------------------------------------------------------------------------------------
//  @brief      手动设置航向角
//  @param      yaw_deg     航向角（度）
//  @return     void
//-------------------------------------------------------------------------------------------------------------------
void ins_api_set_heading(float yaw_deg);

 //------------------------------------------- 轨迹记录 --------------------------------------------------------

//-------------------------------------------------------------------------------------------------------------------
//  @brief      开始记录轨迹点
//  @param      void
//  @return     void
//-------------------------------------------------------------------------------------------------------------------
void ins_api_start_record(void);

//-------------------------------------------------------------------------------------------------------------------
//  @brief      停止记录并 flush 到 Flash
//  @param      void
//  @return     void
//-------------------------------------------------------------------------------------------------------------------
void ins_api_stop_record(void);

//-------------------------------------------------------------------------------------------------------------------
//  @brief      清除所有轨迹数据
//  @param      void
//  @return     void
//-------------------------------------------------------------------------------------------------------------------
void ins_api_clear_track(void);

 //------------------------------------------- 轨迹循迹 --------------------------------------------------------

//-------------------------------------------------------------------------------------------------------------------
//  @brief      开始循迹（自动切换 turn_mode=3）
//  @param      void
//  @return     void
//-------------------------------------------------------------------------------------------------------------------
void ins_api_start_follow(void);

//-------------------------------------------------------------------------------------------------------------------
//  @brief      停止循迹（恢复原 turn_mode）
//  @param      void
//  @return     void
//-------------------------------------------------------------------------------------------------------------------
void ins_api_stop_follow(void);

//-------------------------------------------------------------------------------------------------------------------
//  @brief      设置循迹速度
//  @param      speed_mps   循迹速度（m/s）
//  @return     void
//-------------------------------------------------------------------------------------------------------------------
void ins_api_set_follow_speed(float speed_mps);

 //------------------------------------------- 状态查询 --------------------------------------------------------

const INS_State* ins_api_get_state(void);   // 获取当前 INS 状态
uint32 ins_api_get_track_points(void);       // 获取已存储轨迹点数
uint8 ins_api_is_recording(void);            // 是否正在记录
uint8 ins_api_is_following(void);            // 是否正在循迹

 //------------------------------------------- 循迹转向输出 ----------------------------------------------------

//-------------------------------------------------------------------------------------------------------------------
//  @brief      获取 Pure Pursuit 转向角度
//  @param      void
//  @return     float 转向角度（度），直行返回 0
//-------------------------------------------------------------------------------------------------------------------
float ins_api_get_steer_angle_deg(void);

#endif /* _INS_INTERFACE_H_ */
